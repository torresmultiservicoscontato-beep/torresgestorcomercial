const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const modulo = { exports: {} };
new Function('exports', ts.transpileModule(fs.readFileSync('app/lib/pedidoLotes.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(modulo.exports);
const { atualizarItemPedido: atualizar, itemPedidoParaSalvar: salvar } = modulo.exports;
const base = { produto: 'AC2', tamanhoLote: 88, quantidadeLotes: '', quantidade: '', valorUnitario: '10,50' };
const dois = atualizar(base, 'quantidadeLotes', '2');
assert.equal(dois.quantidade, '176');
assert.equal(dois.valorTotal, '1848.00');
assert.equal(salvar(dois).quantidade, '176');
assert.equal(salvar(dois).tamanhoLote, 88);
assert.equal(salvar(dois).quantidadeLotes, "2");
const reaberto = JSON.parse(JSON.stringify(salvar(dois)));
assert.equal(atualizar(reaberto, "quantidadeLotes", "3").quantidade, "264");
for (const tamanhoLote of [0, -1, NaN, Infinity]) assert.throws(() => salvar({ ...dois, tamanhoLote }));
assert.equal(atualizar(dois, 'quantidadeLotes', '3').quantidade, '264');
assert.equal(atualizar(dois, 'valorUnitario', '2').valorTotal, '352.00');
for (const entrada of ['', '0', '-1', '1.5', 'abc']) assert.throws(() => salvar(atualizar(base, 'quantidadeLotes', entrada)));
assert.equal(atualizar({ ...base, tamanhoLote: 1 }, 'quantidadeLotes', '2').quantidade, '2');
assert.equal(atualizar({ ...base, tamanhoLote: 0.125 }, 'quantidadeLotes', '3').quantidade, '0.375');
const antigo = { produto: 'AC2', quantidade: '176', valorTotal: '1848.00' };
assert.deepEqual(salvar(antigo), antigo);
assert.deepEqual(salvar(salvar(dois)), salvar(dois));
assert.equal(atualizar(dois, 'quantidadeLotes', '').valorTotal, '');
console.log('OK: lotes 88×2/×3, preço por unidade, lote 1/fracionário, entradas inválidas e pedido salvo sem dupla multiplicação.');

const { totalProdutosPedido: total } = modulo.exports;
assert.equal(total([salvar(dois), { produto: 'Outro', valorTotal: '12,90' }]), 1860.9);
assert.equal(total([{ produto: 'A', valorTotal: '0.10' }, { produto: 'B', valorTotal: '0.20' }]), 0.3);
assert.equal(total([]), 0);
assert.equal(total([salvar(dois)]), 1848);
assert.equal(total([{ produto: 'Incompleto', quantidade: '88' }]), null);
assert.equal(total([{ produto: 'Antigo', quantidade: '176', valorUnitario: '10.50' }]), 1848);
assert.equal(total([{ produto: 'Inválido', valorTotal: '-10' }]), null);
console.log('OK: soma de vários produtos, centavos, remoção, item incompleto e quantidade total salva.');
assert.equal(total([atualizar({ ...antigo, valorUnitario: '10.50' }, 'quantidade', '264')]), 2772);
assert.equal(total([atualizar({ ...antigo, valorUnitario: '10.50' }, 'valorUnitario', '2')]), 352);

#!/usr/bin/env node
// Inventário estático. Não consulta projetos nem transforma tipos TS em DDL.
import ts from 'typescript';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const snapshot = fs.readFileSync(path.join(root, 'supabase/schema/production-types.snapshot.ts'), 'utf8');
const ast = ts.createSourceFile('snapshot.ts', snapshot, ts.ScriptTarget.Latest, true);
const declaration = ast.statements.find(s => ts.isTypeAliasDeclaration(s) && s.name.text === 'Database');
function properties(node) { return node?.members ? Array.from(node.members) : []; }
function field(node, name) { return properties(node).find(m => m.name?.getText(ast).replaceAll('"','') === name)?.type; }
function names(node) { return properties(node).map(m => m.name.getText(ast).replaceAll('"','')); }
const publicType = field(declaration.type, 'public');
const tablesType = field(publicType, 'Tables');
const tables = Object.fromEntries(properties(tablesType).map(m => [m.name.getText(ast), names(field(m.type, 'Row'))]));
const functions = names(field(publicType, 'Functions'));
const migrationDir = path.join(root, 'supabase/migrations');
const migrations = fs.readdirSync(migrationDir).filter(f => f.endsWith('.sql')).sort();
const sources = [fs.readFileSync(path.join(root, 'supabase/schema.sql'), 'utf8'), ...migrations.map(f => fs.readFileSync(path.join(migrationDir, f), 'utf8'))];
const definitions = sources.join('\n');
const tableDefinitions = new Set([...definitions.matchAll(/create\s+table\s+(?:if\s+not\s+exists\s+)?public\.([a-z_0-9]+)/gi)].map(m => m[1]));
const functionDefinitions = new Set([...definitions.matchAll(/create\s+(?:or\s+replace\s+)?function\s+public\.([a-z_0-9]+)/gi)].map(m => m[1]));
const versions = Object.groupBy(migrations, f => f.split('_')[0]);
const duplicateVersions = Object.entries(versions).filter(([,files]) => files.length > 1).map(([version,files]) => ({version,files}));
const report = {
  source: 'repository snapshot; not a live production attestation',
  requiredTableCount: Object.keys(tables).length,
  requiredFunctionCount: functions.length,
  missingTableDefinitions: Object.keys(tables).filter(n => !tableDefinitions.has(n)),
  missingFunctionDefinitions: functions.filter(n => !functionDefinitions.has(n)),
  duplicateVersions,
  repositoryCoverageComplete: Object.keys(tables).every(n => tableDefinitions.has(n)) && functions.every(n => functionDefinitions.has(n)) && duplicateVersions.length === 0,
  deploymentReadiness: 'NOT_ATTESTED',
  reason: 'Full schema-only baseline, dependency order and remote permissions require validation before deployment.',
};
function literal(s) { return "'"+s.replaceAll("'","''")+"'"; }
const tableValues = Object.keys(tables).map(n => '('+literal(n)+')').join(',\n');
const columnValues = Object.entries(tables).flatMap(([t,cols]) => cols.map(c => '('+literal(t)+','+literal(c)+')')).join(',\n');
const functionValues = functions.map(n => '('+literal(n)+')').join(',\n');
const sql = `-- Generated by scripts/audit-test-schema.mjs --write-contract. Metadata only.
-- Never treats a TS snapshot as executable schema or as proof of production parity.
BEGIN TRANSACTION READ ONLY;
SET LOCAL statement_timeout = '30s';
WITH expected(name) AS (VALUES ${tableValues})
SELECT 'table' AS kind,e.name AS object,
 CASE WHEN c.oid IS NULL THEN 'MISSING' WHEN NOT c.relrowsecurity THEN 'RLS_DISABLED'
 WHEN NOT EXISTS(SELECT 1 FROM pg_policy p WHERE p.polrelid=c.oid) THEN 'NO_POLICIES'
 WHEN NOT has_table_privilege('authenticated',c.oid,'SELECT') THEN 'NO_AUTHENTICATED_SELECT'
 ELSE 'PRESENT_REQUIRES_POLICY_REVIEW' END AS status
FROM expected e LEFT JOIN pg_namespace n ON n.nspname='public'
LEFT JOIN pg_class c ON c.relnamespace=n.oid AND c.relname=e.name AND c.relkind IN ('r','p') ORDER BY e.name;
WITH expected(table_name,column_name) AS (VALUES ${columnValues})
SELECT 'column' AS kind,e.table_name||'.'||e.column_name AS object,'MISSING' AS status
FROM expected e LEFT JOIN information_schema.columns c
 ON c.table_schema='public' AND c.table_name=e.table_name AND c.column_name=e.column_name
WHERE c.column_name IS NULL ORDER BY 2;
WITH expected(name) AS (VALUES ${functionValues})
SELECT 'function' AS kind,e.name AS object,
 CASE WHEN p.oid IS NULL THEN 'MISSING' ELSE 'PRESENT_REQUIRES_SIGNATURE_AND_GRANT_REVIEW' END AS status
FROM expected e LEFT JOIN pg_namespace n ON n.nspname='public'
LEFT JOIN pg_proc p ON p.pronamespace=n.oid AND p.proname=e.name ORDER BY e.name;
SELECT 'managed_schema' AS kind, name AS object,
 CASE WHEN to_regclass(name) IS NULL THEN 'MISSING' ELSE 'PRESENT' END AS status
FROM (VALUES ('auth.users'),('storage.buckets'),('storage.objects')) e(name);
COMMIT;
`;
if (process.argv.includes('--write-contract')) fs.writeFileSync(path.join(root, 'supabase/tests/required-schema.sql'), sql);
if (process.argv.includes('--check-contract')) {
 if (fs.readFileSync(path.join(root,'supabase/tests/required-schema.sql'),'utf8') !== sql) throw new Error('Schema contract is stale; regenerate it.');
}
console.log(JSON.stringify(report, null, 2));
if (process.argv.includes('--require-coverage') && !report.repositoryCoverageComplete) process.exitCode = 2;
